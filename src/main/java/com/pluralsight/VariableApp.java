package com.pluralsight;

public class VariableApp {
    public static void main(String[] args) {
        // STEP 1
        // Question 1: Declare a variable to store your favorite color
        String favColor = "Lavendar";
        System.out.println("My favorite color is " + favColor + ".");

        //Question 2: Declare a variable to store the year you started this class
        int year = 2026;
        System.out.println("I started this class in " + year + ".");

        // Question 3: Declare a variable to store your middle initial
        char middleInitial = 'C';
        System.out.println("My middle initial is " + middleInitial + ".");

        // Question 4: Declare a variable to store whether you have pets (yes/no)
        boolean pets = false;
        System.out.println("Do I have pets? " + pets);

        // Question 5: Declare a variable with a nice message or saying
        String message = "Have a great day!";
        System.out.println(message);

        // STEP 2
        // 1.
        int days = 7;
        System.out.println("There are " + days + "days in a week.");

        // 2.
        double price = 4.99;
        System.out.println("The price is " + price + ".");

        // 3.
        char favLetter = 'A';
        System.out.println("My favorite letter is " + favLetter + ".");

        // 4.
        boolean isRaining = false;
        System.out.println("Is it raining? " + isRaining);
    }
}
